const tabs = document.querySelector(".tabs");
const days = document.getElementById("days");
const goal = document.getElementById("week-goal");

function el(tag, cls, text) {
  const n = document.createElement(tag);
  if (cls) n.className = cls;
  if (text) n.textContent = text;
  return n;
}

function render(i) {
  const w = WEEKS[i];
  tabs.querySelectorAll("button").forEach((b, j) => b.setAttribute("aria-selected", String(j === i)));
  goal.textContent = w.goal;
  days.replaceChildren();
  for (const [date, wd, items] of w.days) {
    const day = el("div", "day");
    const d = el("div", "day-date", date);
    d.append(el("small", "", wd));
    const list = el("div", "items");
    for (const [code, text, cta] of items) {
      const it = el("div", "item");
      const sw = el("i", `sw sm c-${code}${["ira", "th", "pin", "vk"].includes(code) ? " light" : ""}`);
      const body = el("div", "", text);
      if (cta) body.append(el("span", "cta", cta));
      it.append(sw, el("span", "where", WHERE[code]), body);
      list.append(it);
    }
    day.append(d, list);
    days.append(day);
  }
}

WEEKS.forEach((w, i) => {
  const b = el("button", "", w.title);
  b.type = "button";
  b.setAttribute("role", "tab");
  b.append(el("small", "", w.dates));
  b.addEventListener("click", () => render(i));
  tabs.append(b);
});
render(0);

// подсветка раздела в шапке
const links = [...document.querySelectorAll(".nav a")];
const io = new IntersectionObserver((entries) => {
  for (const e of entries) {
    if (!e.isIntersecting) continue;
    links.forEach((a) => a.classList.toggle("on", a.getAttribute("href") === "#" + e.target.id));
  }
}, { rootMargin: "-40% 0px -55% 0px" });
links.forEach((a) => { const s = document.querySelector(a.getAttribute("href")); if (s) io.observe(s); });
